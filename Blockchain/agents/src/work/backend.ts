/**
 * Backend work, done by code: an OpenAPI 3.1 spec for a resource, the Postgres schema
 * behind it, and Fastify route handlers generated from both. The studio lead then checks
 * the three against each other: every operation has a handler, every field has a column.
 */

export type FieldType = "string" | "text" | "integer" | "number" | "boolean" | "datetime" | "email" | "enum";

export interface Field {
  name: string;
  type: FieldType;
  required?: boolean;
  values?: string[];
}

export interface BackendBrief {
  resource: string;
  fields?: Field[];
  auth?: boolean;
}

export interface Resource {
  name: string;
  plural: string;
  table: string;
  schema: string;
  fields: Field[];
  auth: boolean;
}

const snake = (s: string) =>
  s
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .replace(/^_|_$/g, "")
    .toLowerCase() || "item";
const pascal = (s: string) =>
  snake(s)
    .split("_")
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join("");
const pluralOf = (s: string) => (/(s|x|ch|sh)$/.test(s) ? `${s}es` : /[^aeiou]y$/.test(s) ? `${s.slice(0, -1)}ies` : `${s}s`);

/** Sensible fields when the brief names only the resource. */
const DEFAULTS: Record<string, Field[]> = {
  booking: [
    { name: "guest_name", type: "string", required: true },
    { name: "guest_email", type: "email", required: true },
    { name: "starts_at", type: "datetime", required: true },
    { name: "party_size", type: "integer", required: true },
    { name: "status", type: "enum", values: ["pending", "confirmed", "cancelled"], required: true },
    { name: "notes", type: "text" },
  ],
  order: [
    { name: "customer_email", type: "email", required: true },
    { name: "total_cents", type: "integer", required: true },
    { name: "currency", type: "string", required: true },
    { name: "status", type: "enum", values: ["new", "paid", "shipped", "refunded"], required: true },
    { name: "paid_at", type: "datetime" },
  ],
  task: [
    { name: "title", type: "string", required: true },
    { name: "done", type: "boolean", required: true },
    { name: "priority", type: "enum", values: ["low", "normal", "high"], required: true },
    { name: "due_at", type: "datetime" },
  ],
};

export function resourceOf(brief: BackendBrief): Resource {
  const name = snake(brief.resource);
  const fields = (brief.fields?.length ? brief.fields : (DEFAULTS[name] ?? DEFAULTS.task!)).slice(0, 16).map((f) => ({ ...f, name: snake(f.name) }));
  return { name, plural: pluralOf(name), table: pluralOf(name), schema: pascal(name), fields, auth: brief.auth ?? true };
}

// ------------------------------------------------------------------ OpenAPI

function jsonType(f: Field): Record<string, unknown> {
  switch (f.type) {
    case "integer":
      return { type: "integer" };
    case "number":
      return { type: "number" };
    case "boolean":
      return { type: "boolean" };
    case "datetime":
      return { type: "string", format: "date-time" };
    case "email":
      return { type: "string", format: "email" };
    case "enum":
      return { type: "string", enum: f.values ?? [] };
    case "text":
      return { type: "string", maxLength: 10_000 };
    default:
      return { type: "string", maxLength: 255 };
  }
}

export function writeSpec(r: Resource): Record<string, unknown> {
  const props = Object.fromEntries(r.fields.map((f) => [f.name, jsonType(f)]));
  const required = r.fields.filter((f) => f.required).map((f) => f.name);
  const ref = (n: string) => ({ $ref: `#/components/schemas/${n}` });
  const err = { description: "Error", content: { "application/json": { schema: ref("Error") } } };
  const security = r.auth ? [{ bearer: [] }] : [];
  const idParam = { name: "id", in: "path", required: true, schema: { type: "integer", minimum: 1 } };
  const op = (operationId: string, summary: string, extra: Record<string, unknown>) => ({ operationId, summary, security, ...extra });
  return {
    openapi: "3.1.0",
    info: { title: `${r.schema} API`, version: "1.0.0", description: `CRUD for ${r.plural}. Generated by Quorum's backend studio.` },
    paths: {
      [`/${r.plural}`]: {
        get: op(`list${pascal(r.plural)}`, `List ${r.plural}`, {
          parameters: [
            { name: "limit", in: "query", schema: { type: "integer", minimum: 1, maximum: 100, default: 20 } },
            { name: "offset", in: "query", schema: { type: "integer", minimum: 0, default: 0 } },
          ],
          responses: { "200": { description: "A page", content: { "application/json": { schema: { type: "object", properties: { items: { type: "array", items: ref(r.schema) }, total: { type: "integer" } } } } } }, default: err },
        }),
        post: op(`create${r.schema}`, `Create a ${r.name}`, {
          requestBody: { required: true, content: { "application/json": { schema: ref(`${r.schema}Input`) } } },
          responses: { "201": { description: "Created", content: { "application/json": { schema: ref(r.schema) } } }, "400": err, default: err },
        }),
      },
      [`/${r.plural}/{id}`]: {
        get: op(`get${r.schema}`, `Get one ${r.name}`, { parameters: [idParam], responses: { "200": { description: "Found", content: { "application/json": { schema: ref(r.schema) } } }, "404": err, default: err } }),
        patch: op(`update${r.schema}`, `Update a ${r.name}`, {
          parameters: [idParam],
          requestBody: { required: true, content: { "application/json": { schema: { ...ref(`${r.schema}Input`) } } } },
          responses: { "200": { description: "Updated", content: { "application/json": { schema: ref(r.schema) } } }, "404": err, default: err },
        }),
        delete: op(`delete${r.schema}`, `Delete a ${r.name}`, { parameters: [idParam], responses: { "204": { description: "Deleted" }, "404": err, default: err } }),
      },
    },
    components: {
      schemas: {
        [`${r.schema}Input`]: { type: "object", additionalProperties: false, required, properties: props },
        [r.schema]: { type: "object", required: ["id", ...required, "created_at"], properties: { id: { type: "integer" }, ...props, created_at: { type: "string", format: "date-time" }, updated_at: { type: "string", format: "date-time" } } },
        Error: { type: "object", required: ["error"], properties: { error: { type: "string" } } },
      },
      ...(r.auth ? { securitySchemes: { bearer: { type: "http", scheme: "bearer" } } } : {}),
    },
  };
}

/** Structural checks a spec must pass before anyone builds on it. */
export function lintSpec(spec: Record<string, unknown>): string[] {
  const problems: string[] = [];
  const paths = (spec.paths ?? {}) as Record<string, Record<string, { operationId?: string; responses?: Record<string, unknown> }>>;
  const ids = new Set<string>();
  for (const [p, ops] of Object.entries(paths)) {
    for (const [method, o] of Object.entries(ops)) {
      if (!o.operationId) problems.push(`${method.toUpperCase()} ${p} has no operationId`);
      else if (ids.has(o.operationId)) problems.push(`duplicate operationId ${o.operationId}`);
      else ids.add(o.operationId);
      if (!o.responses || !Object.keys(o.responses).some((c) => /^2/.test(c))) problems.push(`${method.toUpperCase()} ${p} has no success response`);
      for (const param of p.match(/\{(\w+)\}/g) ?? []) {
        const name = param.slice(1, -1);
        const declared = ((o as { parameters?: { name: string; in: string }[] }).parameters ?? []).some((x) => x.name === name && x.in === "path");
        if (!declared) problems.push(`${method.toUpperCase()} ${p} does not declare path parameter ${name}`);
      }
    }
  }
  const refs = JSON.stringify(spec).match(/#\/components\/schemas\/(\w+)/g) ?? [];
  const schemas = ((spec.components as { schemas?: Record<string, unknown> })?.schemas ?? {}) as Record<string, unknown>;
  for (const r of new Set(refs)) if (!schemas[r.split("/").pop()!]) problems.push(`dangling $ref ${r}`);
  return problems;
}

// ------------------------------------------------------------------ SQL

function sqlType(f: Field): string {
  switch (f.type) {
    case "integer":
      return "integer";
    case "number":
      return "numeric(18, 6)";
    case "boolean":
      return "boolean";
    case "datetime":
      return "timestamptz";
    case "text":
      return "text";
    default:
      return "varchar(255)";
  }
}

export function writeSchema(r: Resource): { sql: string; columns: string[]; indexes: string[] } {
  const cols = r.fields.map((f) => {
    const checks: string[] = [];
    if (f.type === "enum" && f.values?.length) checks.push(`check (${f.name} in (${f.values.map((v) => `'${v.replace(/'/g, "''")}'`).join(", ")}))`);
    if (f.type === "email") checks.push(`check (${f.name} ~* '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$')`);
    return `  ${f.name} ${sqlType(f)}${f.required ? " not null" : ""}${checks.length ? ` ${checks.join(" ")}` : ""}`;
  });
  const indexes = r.fields.filter((f) => ["email", "enum", "datetime"].includes(f.type)).map((f) => `create index if not exists ${r.table}_${f.name}_idx on ${r.table} (${f.name});`);
  const sql = [
    `-- ${r.schema}: generated by Quorum's backend studio`,
    `create table if not exists ${r.table} (`,
    ["  id bigint generated always as identity primary key", ...cols, "  created_at timestamptz not null default now()", "  updated_at timestamptz not null default now()"].join(",\n"),
    `);`,
    ...indexes,
    "",
  ].join("\n");
  return { sql, columns: ["id", ...r.fields.map((f) => f.name), "created_at", "updated_at"], indexes };
}

// ------------------------------------------------------------------ code

function zodOf(f: Field): string {
  const base = (() => {
    switch (f.type) {
      case "integer":
        return "z.number().int()";
      case "number":
        return "z.number()";
      case "boolean":
        return "z.boolean()";
      case "datetime":
        return "z.string().datetime()";
      case "email":
        return "z.string().email()";
      case "enum":
        return `z.enum([${(f.values ?? []).map((v) => JSON.stringify(v)).join(", ")}])`;
      case "text":
        return "z.string().max(10000)";
      default:
        return "z.string().max(255)";
    }
  })();
  return f.required ? base : `${base}.optional()`;
}

/** Fastify routes for every operation in the spec, against the table in the schema. */
export function writeCode(r: Resource, spec: Record<string, unknown>): { path: string; content: string; handlers: string[] } {
  const paths = spec.paths as Record<string, Record<string, { operationId: string }>>;
  const ops = Object.entries(paths).flatMap(([p, o]) => Object.entries(o).map(([method, x]) => ({ method, path: p.replace(/\{(\w+)\}/g, ":$1"), id: x.operationId })));
  const cols = r.fields.map((f) => f.name);
  const handler = (o: (typeof ops)[number]): string => {
    const head = `  // ${o.id}\n  app.${o.method}("${o.path}", ${r.auth ? "{ preHandler: requireBearer }, " : ""}async (req, reply) => {`;
    switch (true) {
      case o.method === "get" && !o.path.includes(":id"):
        return `${head}
    const q = Page.parse(req.query);
    const { rows } = await db.query(\`select * from ${r.table} order by id desc limit $1 offset $2\`, [q.limit, q.offset]);
    const { rows: [{ count }] } = await db.query(\`select count(*)::int as count from ${r.table}\`);
    return { items: rows, total: count };
  });`;
      case o.method === "post":
        return `${head}
    const body = Input.parse(req.body);
    const keys = Object.keys(body);
    const { rows } = await db.query(
      \`insert into ${r.table} (\${keys.join(", ")}) values (\${keys.map((_, i) => "$" + (i + 1)).join(", ")}) returning *\`,
      keys.map((k) => body[k as keyof typeof body]),
    );
    return reply.code(201).send(rows[0]);
  });`;
      case o.method === "get":
        return `${head}
    const { id } = Id.parse(req.params);
    const { rows } = await db.query(\`select * from ${r.table} where id = $1\`, [id]);
    return rows[0] ?? reply.code(404).send({ error: "not found" });
  });`;
      case o.method === "patch":
        return `${head}
    const { id } = Id.parse(req.params);
    const body = Input.partial().parse(req.body);
    const keys = Object.keys(body);
    if (keys.length === 0) return reply.code(400).send({ error: "nothing to update" });
    const { rows } = await db.query(
      \`update ${r.table} set \${keys.map((k, i) => k + " = $" + (i + 2)).join(", ")}, updated_at = now() where id = $1 returning *\`,
      [id, ...keys.map((k) => body[k as keyof typeof body])],
    );
    return rows[0] ?? reply.code(404).send({ error: "not found" });
  });`;
      default:
        return `${head}
    const { id } = Id.parse(req.params);
    const { rowCount } = await db.query(\`delete from ${r.table} where id = $1\`, [id]);
    return rowCount ? reply.code(204).send() : reply.code(404).send({ error: "not found" });
  });`;
    }
  };
  const content = `// ${r.schema} API routes: generated by Quorum's backend studio from the OpenAPI spec.
import type { FastifyInstance, FastifyReply, FastifyRequest } from "fastify";
import type { Pool } from "pg";
import { z } from "zod";

const Input = z
  .object({
${r.fields.map((f) => `    ${f.name}: ${zodOf(f)},`).join("\n")}
  })
  .strict();
const Id = z.object({ id: z.coerce.number().int().min(1) });
const Page = z.object({ limit: z.coerce.number().int().min(1).max(100).default(20), offset: z.coerce.number().int().min(0).default(0) });
/** Columns this module writes: ${cols.join(", ")} */
${
  r.auth
    ? `
async function requireBearer(req: FastifyRequest, reply: FastifyReply) {
  const token = req.headers.authorization?.replace(/^Bearer /, "");
  if (!token || token !== process.env.API_TOKEN) return reply.code(401).send({ error: "unauthorized" });
}
`
    : ""
}
export function ${r.name}Routes(app: FastifyInstance, db: Pool): void {
  app.setErrorHandler((err, _req, reply) => {
    if (err instanceof z.ZodError) return reply.code(400).send({ error: err.issues.map((i) => i.path.join(".") + ": " + i.message).join("; ") });
    reply.code(500).send({ error: "internal error" });
  });

${ops.map(handler).join("\n\n")}
}
`;
  return { path: `src/routes/${r.plural}.ts`, content, handlers: ops.map((o) => o.id) };
}

/** The lead's acceptance check: the three deliverables describe the same API. */
export function crossCheck(r: Resource, spec: Record<string, unknown>, schema: { columns: string[] }, code: { content: string }): string[] {
  const problems = lintSpec(spec);
  const paths = spec.paths as Record<string, Record<string, { operationId: string }>>;
  for (const ops of Object.values(paths)) for (const o of Object.values(ops)) if (!code.content.includes(`// ${o.operationId}\n`)) problems.push(`no handler for ${o.operationId}`);
  const input = ((spec.components as { schemas: Record<string, { properties?: Record<string, unknown> }> }).schemas[`${r.schema}Input`]?.properties ?? {}) as Record<string, unknown>;
  for (const field of Object.keys(input)) {
    if (!schema.columns.includes(field)) problems.push(`field ${field} has no column`);
    if (!new RegExp(`\\b${field}:`).test(code.content)) problems.push(`field ${field} is not validated in the code`);
  }
  return problems;
}
